#!/usr/bin/env python3
"""The build stamp: which commit a DLL comes from, and whether the tree was clean.

    python tools/build_stamp.py                 print the stamp, one line
    python tools/build_stamp.py --json          print it as JSON
    python tools/build_stamp.py --write DIR     write DIR/BridgeStamp.g.cs and DIR/BridgeStamp.json

build.cmd calls --write once, before the solution build, and passes the .cs file to every
project (-p:BridgeStampFile=...). Every assembly then carries the same three facts:

    AssemblyInformationalVersion   "<mod version>+<git sha>"   (".dirty" appended on a dirty tree)
    AssemblyMetadata KRPC.Bridge.GitSha       the 40-hex commit
    AssemblyMetadata KRPC.Bridge.GitDirty     "0" clean, "1" dirty or unknown
    AssemblyMetadata KRPC.Bridge.SourceDate   the commit's date, UTC, ISO 8601

WHY THE COMMIT DATE AND NOT THE BUILD TIME. The builds are deterministic: the same commit
gives the same bytes, which is how a tree is proven to be what flies without flying it. A
wall-clock time inside the DLL would make every build unique and end that. The commit date is
the reproducible-builds convention (SOURCE_DATE_EPOCH); a dirty build says so in GitDirty.

DIRTY means any change git reports: a modified or staged tracked file, or an untracked file
that is not ignored (EnableDefaultCompileItems compiles every .cs, tracked or not). Without
git (a source zip), the stamp is "unknown" and dirty.
"""

import io
import json
import os
import subprocess
import sys
import time

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# Paths a tool writes and no build reads, which must not make a tree dirty (none today).
NOT_DIRTYING = ()

UNKNOWN_SHA = "unknown"

META_SHA = "KRPC.Bridge.GitSha"
META_DIRTY = "KRPC.Bridge.GitDirty"
META_DATE = "KRPC.Bridge.SourceDate"


def _git(args, cwd=ROOT):
    """Output of a git command, or None when git is missing or fails."""
    try:
        out = subprocess.run(["git"] + list(args), cwd=cwd, stdout=subprocess.PIPE,
                             stderr=subprocess.PIPE, check=False)
    except OSError:
        return None
    if out.returncode != 0:
        return None
    return out.stdout.decode("utf-8", "replace")


def dirty_paths(cwd=ROOT):
    """The paths that make the tree dirty (empty list: clean), or None without git."""
    # "all", not "normal": an untracked folder must list its files, not read as one
    # directory name.
    out = _git(["status", "--porcelain", "--untracked-files=all"], cwd)
    if out is None:
        return None
    paths = []
    for line in out.splitlines():
        if len(line) < 4:
            continue
        path = line[3:].strip().strip('"')
        if " -> " in path:                 # a rename: the new name is what counts
            path = path.split(" -> ", 1)[1].strip('"')
        if path.replace("\\", "/") in NOT_DIRTYING:
            continue
        paths.append(path)
    return paths


def mod_version(root=ROOT):
    """MAJOR.MINOR.PATCH from distribution/KRPC.Bridge.version, or "0.0.0"."""
    try:
        with io.open(os.path.join(root, "distribution", "KRPC.Bridge.version"),
                     encoding="utf-8") as handle:
            v = json.load(handle).get("VERSION", {})
        return "%d.%d.%d" % (int(v.get("MAJOR", 0)), int(v.get("MINOR", 0)),
                             int(v.get("PATCH", 0)))
    except (OSError, ValueError, TypeError):
        return "0.0.0"


def compute(cwd=ROOT):
    """The stamp of the tree at cwd, as a dict."""
    sha = (_git(["rev-parse", "HEAD"], cwd) or "").strip()
    epoch = (_git(["show", "-s", "--format=%ct", "HEAD"], cwd) or "").strip()
    dirty = dirty_paths(cwd)
    if len(sha) != 40:
        sha = UNKNOWN_SHA
    date = ""
    if epoch.isdigit():
        date = time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime(int(epoch)))
    known = sha != UNKNOWN_SHA and dirty is not None
    is_dirty = (not known) or bool(dirty)
    version = mod_version(cwd)
    informational = "%s+%s%s" % (version, sha, ".dirty" if is_dirty else "")
    return {
        "git_sha": sha,
        "git_dirty": is_dirty,
        "dirty_paths": sorted(dirty or []),
        "source_date": date,
        "mod_version": version,
        "informational_version": informational,
    }


def _cs_string(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def render_cs(stamp):
    """The C# file every project compiles. Deterministic: no time, no path."""
    lines = [
        "// <auto-generated>",
        "// Written by tools/build_stamp.py for build.cmd. Do not edit, do not commit.",
        "// </auto-generated>",
        "[assembly: System.Reflection.AssemblyInformationalVersion (%s)]"
        % _cs_string(stamp["informational_version"]),
        "[assembly: System.Reflection.AssemblyMetadata (%s, %s)]"
        % (_cs_string(META_SHA), _cs_string(stamp["git_sha"])),
        "[assembly: System.Reflection.AssemblyMetadata (%s, %s)]"
        % (_cs_string(META_DIRTY), _cs_string("1" if stamp["git_dirty"] else "0")),
        "[assembly: System.Reflection.AssemblyMetadata (%s, %s)]"
        % (_cs_string(META_DATE), _cs_string(stamp["source_date"])),
    ]
    return "\n".join(lines) + "\n"


def _write_if_changed(path, data):
    """Write bytes only when they differ, so an unchanged stamp keeps the build incremental."""
    try:
        with io.open(path, "rb") as handle:
            if handle.read() == data:
                return False
    except OSError:
        pass
    with io.open(path, "wb") as handle:
        handle.write(data)
    return True


def write(directory, stamp):
    """DIR/BridgeStamp.g.cs (compiled) and DIR/BridgeStamp.json (read by tools/manifest.py)."""
    if not os.path.isdir(directory):
        os.makedirs(directory)
    _write_if_changed(os.path.join(directory, "BridgeStamp.g.cs"),
                      render_cs(stamp).encode("utf-8"))
    _write_if_changed(os.path.join(directory, "BridgeStamp.json"),
                      (json.dumps(stamp, indent=2, sort_keys=True) + "\n").encode("utf-8"))


def describe(stamp):
    state = "DIRTY" if stamp["git_dirty"] else "clean"
    line = "%s %s %s (%s)" % (stamp["git_sha"], state, stamp["source_date"] or "-",
                              stamp["informational_version"])
    if stamp["dirty_paths"]:
        shown = stamp["dirty_paths"][:8]
        more = len(stamp["dirty_paths"]) - len(shown)
        line += "\n  dirty: " + ", ".join(shown) + (" (+%d)" % more if more > 0 else "")
    return line


def main(argv):
    stamp = compute()
    if len(argv) >= 2 and argv[0] == "--write":
        write(argv[1], stamp)
        print("  stamp " + describe(stamp))
        return 0
    if argv and argv[0] == "--json":
        print(json.dumps(stamp, indent=2, sort_keys=True))
        return 0
    if argv:
        print(__doc__)
        return 2
    print(describe(stamp))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
